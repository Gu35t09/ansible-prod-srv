#!/bin/bash
# Refreshes the YARA rules vendored in roles/yara/files/rules from their
# upstream repositories, at the commits pinned below. Run it on the controller
# (the server has no route to GitHub), review the diff, then commit.
#
# Usage: scripts/update-yara-rules.sh [ESET_COMMIT] [ELASTIC_COMMIT]
# Without arguments it fetches the pinned commits again. To move to newer
# rules, pass the new commit IDs and update the pins below.
set -euo pipefail

ESET_REPO=https://github.com/eset/malware-ioc.git
ESET_COMMIT=${1:-59745502656e813f9f79fc8005243edbc04f9397}
# Ebury and the OpenSSH backdoors described by ESET.
ESET_FILES=(windigo/ebury.yar sshdoor/sshdoor.yar)

ELASTIC_REPO=https://github.com/elastic/protections-artifacts.git
ELASTIC_COMMIT=${2:-c7b3b2eb7fe9a0c73282003d81da4c0e2d32941d}
# Every Linux rule and the cross-platform ones (miners, C2 implants, tunnels,
# ransomware), except the attack-simulation tool, which is not malware.
ELASTIC_INCLUDE='^(Linux|Multi)_.*\.yar$'
ELASTIC_EXCLUDE='^Multi_AttackSimulation_'

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEST="$ROOT/roles/yara/files/rules"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# Shallow, blob-less fetch of a single commit, then checkout of the given paths.
fetch() {
    local repo=$1 commit=$2 dir=$3
    shift 3
    git -C "$WORK" init -q "$dir"
    git -C "$WORK/$dir" remote add origin "$repo"
    git -C "$WORK/$dir" fetch -q --depth 1 --filter=blob:none origin "$commit"
    git -C "$WORK/$dir" sparse-checkout set --no-cone "$@"
    git -C "$WORK/$dir" checkout -q FETCH_HEAD
}

fetch "$ESET_REPO" "$ESET_COMMIT" eset "${ESET_FILES[@]}" /LICENSE
fetch "$ELASTIC_REPO" "$ELASTIC_COMMIT" elastic /yara/rules/ /LICENSE.txt

rm -rf "$DEST"
mkdir -p "$DEST/eset" "$DEST/elastic"

for file in "${ESET_FILES[@]}"; do
    cp "$WORK/eset/$file" "$DEST/eset/"
done
cp "$WORK/eset/LICENSE" "$DEST/eset/LICENSE"

find "$WORK/elastic/yara/rules" -maxdepth 1 -type f -printf '%f\n' \
    | grep -E "$ELASTIC_INCLUDE" | grep -Ev "$ELASTIC_EXCLUDE" | sort \
    | while read -r file; do cp "$WORK/elastic/yara/rules/$file" "$DEST/elastic/"; done
cp "$WORK/elastic/LICENSE.txt" "$DEST/elastic/LICENSE.txt"

cat > "$DEST/SOURCES.md" <<EOF
# YARA rule sources

Generated by \`scripts/update-yara-rules.sh\` on $(date -u +%Y-%m-%d). Do not edit
the rule files by hand: run the script again instead.

| Directory | Upstream | Commit | License |
| --- | --- | --- | --- |
| \`eset/\` | $ESET_REPO | \`$ESET_COMMIT\` | BSD 2-Clause (\`eset/LICENSE\`) |
| \`elastic/\` | $ELASTIC_REPO | \`$ELASTIC_COMMIT\` | Elastic License 2.0 (\`elastic/LICENSE.txt\`) |

Files: $(find "$DEST/eset" -name '*.yar' | wc -l) from ESET, $(find "$DEST/elastic" -name '*.yar' | wc -l) from Elastic.
EOF

echo "Rules written to $DEST:"
cat "$DEST/SOURCES.md"
